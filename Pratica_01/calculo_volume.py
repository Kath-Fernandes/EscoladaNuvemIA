"""
3- Calculadora de Volume
Crie um programa que calcule o volume de uma caixa retangular. Use as seguintes dimensões:
Comprimento: 12 cm
Largura: 14 cm
Altura: 20 cm O programa deve calcular o volume e exibir o resultado em cm³.
Cálculo do volume
volume = comprimento * largura * altura
O programa deve calcular e exibir o resultado em cm³
"""

# Definindo variáveis
comprimento = 12
largura = 14
altura = 20

# Cálculo do volume
volume = comprimento * largura * altura

# Exibir o resultado
print(f"O volume da caixa é de {volume} cm³")